static const uint8_t rcon[11] = {0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36};

static void key_expansion(const uint8_t* key, uint8_t* round_keys) {
    std::memcpy(round_keys, key, 16);
    for (int i = 4; i < 44; ++i) {
        uint8_t temp[4];
        std::memcpy(temp, round_keys + (i - 1) * 4, 4);
        if (i % 4 == 0) {
            uint8_t t = temp[0];
            temp[0] = sbox[temp[1]] ^ rcon[i / 4];
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[t];
        }
        for (int j = 0; j < 4; ++j) {
            round_keys[i * 4 + j] = round_keys[(i - 4) * 4 + j] ^ temp[j];
        }
    }
}

static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int counter = 0; counter < 8; counter++) {
        if ((b & 1) != 0)
            p ^= a;
        bool hi_bit_set = (a & 0x80) != 0;
        a <<= 1;
        if (hi_bit_set)
            a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

static void encrypt_block(const uint8_t* in, uint8_t* out, const uint8_t* round_keys) {
    uint8_t state[16];
    std::memcpy(state, in, 16);

    for (int i = 0; i < 16; ++i)
        state[i] ^= round_keys[i];

    for (int round = 1; round < 10; ++round) {
        // SubBytes
        for (int i = 0; i < 16; ++i)
            state[i] = sbox[state[i]];

        // ShiftRows
        uint8_t temp[16];
        temp[0] = state[0];
        temp[4] = state[4];
        temp[8] = state[8];
        temp[12] = state[12];
        temp[1] = state[5];
        temp[5] = state[9];
        temp[9] = state[13];
        temp[13] = state[1];
        temp[2] = state[10];
        temp[6] = state[14];
        temp[10] = state[2];
        temp[14] = state[6];
        temp[3] = state[15];
        temp[7] = state[3];
        temp[11] = state[7];
        temp[15] = state[11];

        // MixColumns
        for (int i = 0; i < 4; ++i) {
            uint8_t a = temp[i * 4 + 0], b = temp[i * 4 + 1], c = temp[i * 4 + 2], d = temp[i * 4 + 3];
            state[i * 4 + 0] = gmul(a, 2) ^ gmul(b, 3) ^ c ^ d;
            state[i * 4 + 1] = a ^ gmul(b, 2) ^ gmul(c, 3) ^ d;
            state[i * 4 + 2] = a ^ b ^ gmul(c, 2) ^ gmul(d, 3);
            state[i * 4 + 3] = gmul(a, 3) ^ b ^ c ^ gmul(d, 2);
        }

        // AddRoundKey
        for (int i = 0; i < 16; ++i)
            state[i] ^= round_keys[round * 16 + i];
    }

    // Final round
    for (int i = 0; i < 16; ++i)
        state[i] = sbox[state[i]];

    uint8_t temp[16];
    temp[0] = state[0];
    temp[4] = state[4];
    temp[8] = state[8];
    temp[12] = state[12];
    temp[1] = state[5];
    temp[5] = state[9];
    temp[9] = state[13];
    temp[13] = state[1];
    temp[2] = state[10];
    temp[6] = state[14];
    temp[10] = state[2];
    temp[14] = state[6];
    temp[3] = state[15];
    temp[7] = state[3];
    temp[11] = state[7];
    temp[15] = state[11];

    for (int i = 0; i < 16; ++i)
        out[i] = temp[i] ^ round_keys[160 + i];
}

static void decrypt_block(const uint8_t* in, uint8_t* out, const uint8_t* round_keys) {
    uint8_t state[16];
    std::memcpy(state, in, 16);

    for (int i = 0; i < 16; ++i)
        state[i] ^= round_keys[160 + i];

    for (int round = 9; round >= 1; --round) {
        // InvShiftRows
        uint8_t temp[16];
        temp[0] = state[0];
        temp[4] = state[4];
        temp[8] = state[8];
        temp[12] = state[12];
        temp[1] = state[13];
        temp[5] = state[1];
        temp[9] = state[5];
        temp[13] = state[9];
        temp[2] = state[10];
        temp[6] = state[14];
        temp[10] = state[2];
        temp[14] = state[6];
        temp[3] = state[7];
        temp[7] = state[11];
        temp[11] = state[15];
        temp[15] = state[3];

        // InvSubBytes
        for (int i = 0; i < 16; ++i)
            state[i] = rsbox[temp[i]];

        // AddRoundKey
        for (int i = 0; i < 16; ++i)
            state[i] ^= round_keys[round * 16 + i];

        // InvMixColumns
        for (int i = 0; i < 4; ++i) {
            uint8_t a = state[i * 4 + 0], b = state[i * 4 + 1], c = state[i * 4 + 2], d = state[i * 4 + 3];
            temp[i * 4 + 0] = gmul(a, 0x0e) ^ gmul(b, 0x0b) ^ gmul(c, 0x0d) ^ gmul(d, 0x09);
            temp[i * 4 + 1] = gmul(a, 0x09) ^ gmul(b, 0x0e) ^ gmul(c, 0x0b) ^ gmul(d, 0x0d);
            temp[i * 4 + 2] = gmul(a, 0x0d) ^ gmul(b, 0x09) ^ gmul(c, 0x0e) ^ gmul(d, 0x0b);
            temp[i * 4 + 3] = gmul(a, 0x0b) ^ gmul(b, 0x0d) ^ gmul(c, 0x09) ^ gmul(d, 0x0e);
        }
        std::memcpy(state, temp, 16);
    }

    // Final round
    uint8_t temp[16];
    temp[0] = state[0];
    temp[4] = state[4];
    temp[8] = state[8];
    temp[12] = state[12];
    temp[1] = state[13];
    temp[5] = state[1];
    temp[9] = state[5];
    temp[13] = state[9];
    temp[2] = state[10];
    temp[6] = state[14];
    temp[10] = state[2];
    temp[14] = state[6];
    temp[3] = state[7];
    temp[7] = state[11];
    temp[11] = state[15];
    temp[15] = state[3];

    for (int i = 0; i < 16; ++i)
        out[i] = rsbox[temp[i]] ^ round_keys[i];
}

std::vector<uint8_t> AES128::encrypt_ecb(const uint8_t* key, const uint8_t* data, size_t len) {
    if (!key || !data || len == 0 || (len % 16) != 0)
        return {};
    uint8_t round_keys[176];
    key_expansion(key, round_keys);

    std::vector<uint8_t> out(len);
    for (size_t i = 0; i < len; i += 16) {
        encrypt_block(data + i, out.data() + i, round_keys);
    }
    return out;
}

std::vector<uint8_t> AES128::encrypt_cbc(const uint8_t* key, const uint8_t* iv, const uint8_t* data, size_t len) {
    if (!key || !data || len == 0 || (len % 16) != 0)
        return {};
    uint8_t round_keys[176];
    key_expansion(key, round_keys);

    std::vector<uint8_t> out(len);
    uint8_t prev_block[16];
    if (iv)
        std::memcpy(prev_block, iv, 16);
    else
        std::memset(prev_block, 0, 16);

    for (size_t i = 0; i < len; i += 16) {
        uint8_t block[16];
        for (int j = 0; j < 16; ++j) {
            block[j] = data[i + j] ^ prev_block[j];
        }
        encrypt_block(block, out.data() + i, round_keys);
        std::memcpy(prev_block, out.data() + i, 16);
    }
    return out;
}

std::vector<uint8_t> AES128::decrypt_cbc(const uint8_t* key, const uint8_t* iv, const uint8_t* data, size_t len) {
    if (!key || !data || len == 0 || (len % 16) != 0)
        return {};
    uint8_t round_keys[176];
    key_expansion(key, round_keys);

    std::vector<uint8_t> out(len);
    uint8_t prev_block[16];
    if (iv)
        std::memcpy(prev_block, iv, 16);
    else
        std::memset(prev_block, 0, 16);

    for (size_t i = 0; i < len; i += 16) {
        uint8_t block[16];
        decrypt_block(data + i, block, round_keys);
        for (int j = 0; j < 16; ++j) {
            out[i + j] = block[j] ^ prev_block[j];
        }
        std::memcpy(prev_block, data + i, 16);
    }
    return out;
}

std::vector<uint8_t> AES128::decrypt_ecb(const uint8_t* key, const uint8_t* data, size_t len) {
    if (!key || !data || len == 0 || (len % 16) != 0)
        return {};
    uint8_t round_keys[176];
    key_expansion(key, round_keys);

    std::vector<uint8_t> out(len);
    for (size_t i = 0; i < len; i += 16) {
        decrypt_block(data + i, out.data() + i, round_keys);
    }
    return out;
}

